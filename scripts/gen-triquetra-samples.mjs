// Generate src/data/triquetraSamples.ts: the triquetra path samples the worlds
// used to compute at runtime with SVG getTotalLength/getPointAtLength (the
// single biggest main-thread cost at load). The sampling runs in real Chrome,
// on the same detached <path> the components used, at each consumer's own
// density, so the numbers are exactly what the browser produced, rounded to 5
// decimals (TRIQUETRA_DECIMALS overrides). Why 5, not 3: the loops contain
// zero-length segments ("h0"), where consecutive samples sit a hair apart;
// rounding to 3 decimals can merge them or flip the tiny segment's direction,
// and World 01's canvas stroke then renders a visible 1px kink at the join.
// At 5 decimals the rendering matches the old runtime sampling to within one
// antialiasing level (max channel delta 1/255).
//
//   bun run gen:triquetra     (re-run whenever TRIQUETRA_LOOPS or the viewBox change;
//                              production builds fail while the file is stale)
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import puppeteer from "puppeteer-core";

const CHROME = process.env.CHROME_PATH || "C:/Program Files/Google/Chrome/Application/chrome.exe";
const SRC = "src/data/triquetra.ts";
const OUT = "src/data/triquetraSamples.ts";

// --- the source strings, read from triquetra.ts (the single source of truth)
const src = readFileSync(SRC, "utf8");
const viewBox = src.match(/export const TRIQUETRA_VIEWBOX = "([^"]+)";/)?.[1];
const loopsBlock = src.match(/export const TRIQUETRA_LOOPS: string\[\] = \[([\s\S]*?)\n\];/)?.[1];
const loops = loopsBlock ? [...loopsBlock.matchAll(/^\s*"([^"]+)",?\s*$/gm)].map((m) => m[1]) : [];
if (!viewBox || loops.length !== 3) throw new Error(`could not read TRIQUETRA_VIEWBOX / 3 TRIQUETRA_LOOPS from ${SRC}`);

// Must match the hash vite.config.ts recomputes on production builds.
const sourceHash = createHash("sha256").update(JSON.stringify({ viewBox, loops })).digest("hex").slice(0, 16);

// --- sample in the browser, exactly as the components did ------------------
const browser = await puppeteer.launch({ executablePath: CHROME, headless: "new" });
const page = await browser.newPage();
const raw = await page.evaluate((loops) => {
  const path = document.createElementNS("http://www.w3.org/2000/svg", "path");
  const sample = (d, stepsFor) => {
    path.setAttribute("d", d);
    const len = path.getTotalLength();
    const steps = stepsFor(len);
    const pts = [];
    for (let i = 0; i <= steps; i++) {
      const p = path.getPointAtLength((i / steps) * len);
      pts.push([p.x, p.y]);
    }
    return { len, pts };
  };
  // WorldCreative: steps = max(96, round(len / 3)); lengths reused for timing
  const creative = loops.map((d) => sample(d, (len) => Math.max(96, Math.round(len / 3))));
  // WorldLogic buildGeometry: steps = max(64, round(len / 6)) → centroids + bbox
  let lMinX = Infinity, lMinY = Infinity, lMaxX = -Infinity, lMaxY = -Infinity;
  const centroids = loops.map((d) => {
    const { pts } = sample(d, (len) => Math.max(64, Math.round(len / 6)));
    let sx = 0, sy = 0;
    for (const [x, y] of pts) {
      sx += x; sy += y;
      if (x < lMinX) lMinX = x; if (x > lMaxX) lMaxX = x;
      if (y < lMinY) lMinY = y; if (y > lMaxY) lMaxY = y;
    }
    return [sx / pts.length, sy / pts.length];
  });
  return {
    lengths: creative.map((c) => c.len),
    creativePts: creative.map((c) => c.pts),
    centroids,
    logicBBox: { minX: lMinX, minY: lMinY, maxX: lMaxX, maxY: lMaxY },
  };
}, loops);
await browser.close();

// --- round to DECIMALS places, tracking the worst deviation -----------------
const DECIMALS = Number(process.env.TRIQUETRA_DECIMALS ?? 5);
const SCALE = 10 ** DECIMALS;
let maxDev = 0;
const r3 = (v) => {
  const r = Math.round(v * SCALE) / SCALE;
  maxDev = Math.max(maxDev, Math.abs(r - v));
  return r;
};
const lengths = raw.lengths.map(r3);
const creativeFlat = raw.creativePts.map((pts) => pts.flat().map(r3));
const centroids = raw.centroids.map(([x, y]) => ({ x: r3(x), y: r3(y) }));
const lb = raw.logicBBox;
const logicBBox = { minX: r3(lb.minX), minY: r3(lb.minY), maxX: r3(lb.maxX), maxY: r3(lb.maxY) };

const arr = (a) => `[${a.join(",")}]`;
const out = `// GENERATED by scripts/gen-triquetra-samples.mjs (\`bun run gen:triquetra\`).
// Do not edit by hand. Re-generate whenever TRIQUETRA_LOOPS or TRIQUETRA_VIEWBOX
// in ./triquetra.ts change; production builds fail while SOURCE_HASH is stale.
//
// The browser's own SVG getTotalLength/getPointAtLength samples of the three
// triquetra loops (a detached <path>, in Chrome), at each consumer's density,
// rounded to ${DECIMALS} decimals. Precomputed because sampling at load was the largest
// main-thread cost on mobile.

/** sha256(JSON.stringify({ viewBox, loops })).slice(0, 16) of the source paths. */
export const SOURCE_HASH = "${sourceHash}";

/** getTotalLength() of each loop, in viewBox units. */
export const LOOP_LENGTHS: readonly number[] = ${arr(lengths)};

/**
 * WorldCreative density: per loop, max(96, round(len / 3)) + 1 points, flat
 * [x0, y0, x1, y1, …] in viewBox units.
 */
export const LOOP_POINTS_CREATIVE: readonly (readonly number[])[] = [
${creativeFlat.map((a) => `  ${arr(a)},`).join("\n")}
];

/** WorldLogic density (max(64, round(len / 6)) + 1 points): each loop's centroid. */
export const LOOP_CENTROIDS: readonly { x: number; y: number }[] = ${JSON.stringify(centroids)};

/** WorldLogic density: min/max of all sampled points across the three loops. */
export const MARK_BBOX = ${JSON.stringify(logicBBox)} as const;
`;
writeFileSync(OUT, out);
const pts = creativeFlat.reduce((n, a) => n + a.length / 2, 0);
console.log(`wrote ${OUT}: ${out.length} bytes, ${pts} creative points, hash ${sourceHash}, max rounding deviation ${maxDev.toExponential(3)}`);
